    public static let all: [Card] = easy + medium + hard

    public static func pool(_ difficulty: Difficulty) -> [Card] {
        switch difficulty { case .easy: easy; case .medium: medium; case .hard: hard }
    }

    public static func card(id: String) -> Card? { all.first { $0.id == id } }

    private static func make(_ prefix: String, _ difficulty: Difficulty, _ rows: [(String, String, Category)]) -> [Card] {
        rows.enumerated().map { index, row in
            Card(id: String(format: "daily-%@-%03d", prefix, index + 1), wordFull: row.0, hint: row.1, category: row.2, difficulty: difficulty)
        }
    }
